"""SAR Change project page: picture-first sections that replace the default 'satellite', 'actions' and 'impact' sections.
All numbers come from app.json / zones.json (generated by prep/*.py from NASA OPERA DSWx-S1 and demos/sar-change/data/metrics.json)."""
import json
from html import escape as e
from pathlib import Path
D = Path(__file__).resolve().parent
APPJ = json.loads((D / "app.json").read_text()); Z = json.loads((D / "zones.json").read_text())
K = APPJ["kpi"]; ACTS = APPJ["actions"]; IMP = APPJ["impact"]; ZN = {z["name"]: z for z in Z["zones"]}
W, H = Z["totals"]["size"]
IMG = "/sar-change/m/img/"
f1 = lambda v: f"{v:.1f}"
SW = {"new": "#38bdf8", "perm": "#1e40af", "land": "#262c46", "kept": "#0e7490", "gone": "#f59e0b"}
def legend(items, cls=""):
    return f'<div class="sl-legend {cls}">' + "".join(f'<span><i style="background:{SW[k]}"></i>{e(t)}</span>' for k, t in items) + "</div>"
L_WATER = [("new", "New flood water"), ("perm", "Usual water: sea, lagoon, rivers"), ("land", "Dry land")]
L_DELTA = [("new", "Newly wet since 26 Oct"), ("kept", "Wet on both dates"), ("gone", "Dried out"), ("perm", "Usual water")]
def side(lr, k, d, v):
    dd, _, sn = d.partition(" · ")
    return f'<div class="sl-side {lr}"><b>{e(k)}</b><span>{e(dd)}{f"<small> · {e(sn)}</small>" if sn else ""}</span><em>{e(v)}</em></div>'
def step_head(n, kicker, title):
    return f'<div class="step-head" data-fx="rise"><span class="step-n">{n}</span><p class="eyebrow">{e(kicker)}</p>{f"<h2>{e(title)}</h2>" if title else ""}</div>'
def zones_svg(names, alt=(), cls="sl-zones"):
    on, al = set(names), set(alt)
    paths = "".join(f'<path class="{"on" if z["name"] in on else "alt" if z["name"] in al else ""}" d="{z["d"]}" vector-effect="non-scaling-stroke"/>' for z in Z["zones"] if z["name"] in on or z["name"] in al or z["new_after_km2"] >= 0.1)
    return f'<svg class="{cls}" viewBox="0 0 {W} {H}" preserveAspectRatio="none" aria-hidden="true">{paths}</svg>'

ICON = {  # same line icons as the shared C2 component
 "drone": '<path d="M5 5l4 4m6 6 4 4M19 5l-4 4M9 15l-4 4"/><circle cx="5" cy="5" r="2.2"/><circle cx="19" cy="5" r="2.2"/><circle cx="5" cy="19" r="2.2"/><circle cx="19" cy="19" r="2.2"/><rect x="9" y="9" width="6" height="6" rx="1.5"/>',
 "camera": '<path d="M3 8h4l2-3h6l2 3h4v11H3z"/><circle cx="12" cy="13" r="3.5"/>',
 "satellite": '<path d="M13 7l4 4-6 6-4-4z"/><path d="M7 13l-4 4m14-6 4-4M10 4l3 3M17 11l3 3"/><path d="M15 19a5 5 0 0 0 4-4"/>',
 "crew": '<circle cx="8" cy="8" r="3"/><circle cx="16" cy="9" r="2.5"/><path d="M2.5 20a5.5 5.5 0 0 1 11 0M13 20a4 4 0 0 1 8 0"/>',
 "notice": '<path d="M4 10v4h3l6 4V6L7 10z"/><path d="M17 9a4 4 0 0 1 0 6M19.5 6.5a7.5 7.5 0 0 1 0 11"/>',
 "engineer": '<path d="M4 20h16M6 20V10l6-5 6 5v10"/><path d="M10 20v-5h4v5"/>',
 "sensor": '<circle cx="12" cy="12" r="2"/><path d="M8 8a5.5 5.5 0 0 0 0 8M16 8a5.5 5.5 0 0 1 0 8M5 5a10 10 0 0 0 0 14M19 5a10 10 0 0 1 0 14"/>',
 "plan": '<rect x="5" y="3" width="14" height="18" rx="2"/><path d="M9 8h6M9 12h6M9 16h4"/>',
 "truck": '<path d="M2 6h11v10H2zM13 10h4l3 3v3h-7z"/><circle cx="6" cy="17.5" r="1.8"/><circle cx="16.5" cy="17.5" r="1.8"/>'}
icon = lambda k: f'<svg class="sl-ico" viewBox="0 0 24 24" aria-hidden="true" fill="none" stroke="currentColor" stroke-width="1.6" stroke-linecap="round" stroke-linejoin="round">{ICON.get(k, ICON["plan"])}</svg>'

def satellite():
    swipe = (f'<figure class="sl-fig" data-fx="rise"><div class="ba sl-ba"><img src="{IMG}opera-before.webp" alt="Water on 26 Oct 2024 from NASA OPERA radar" width="{W}" height="{H}" />'
             f'<img class="after" src="{IMG}opera-after.webp" alt="Water on 31 Oct 2024 from NASA OPERA radar" width="{W}" height="{H}" />{zones_svg([])}'
             + side("l", "Before", "26 Oct 2024 · Sentinel-1A radar", f"{f1(K['before'])} km² new water")
             + side("r", "After", "31 Oct 2024 · Sentinel-1A radar", f"{f1(K['after'])} km² new water")
             + f'<span class="handle" aria-hidden="true"></span><input type="range" min="0" max="100" value="50" aria-label="Compare 26 Oct and 31 Oct" />{legend(L_WATER, "on")}</div>{legend(L_WATER, "below")}'
             f'<figcaption>Drag to compare. NASA/JPL OPERA DSWx-S1 surface water, 30 m, from Sentinel-1 radar, which sees through cloud. Town outlines © OpenStreetMap.</figcaption></figure>')
    steps = [("before", "26 Oct · 3 days before", f1(K["before"]), "km² of new water", "The rice paddies around the Albufera lagoon were already filling for the season."),
             ("after", "31 Oct · 2 days after the storm", f1(K["after"]), "km² of new water", "Seen through cloud, two days after the 29 October storm, while optical satellites saw only cloud."),
             ("delta", "What changed", "+" + f1(K["net"]), "km² in five days", f"{f1(K['added'])} km² newly wet, {f1(K['kept'])} km² wet on both dates, {f1(K['gone'])} km² dried out."),
             ("still", "19 Nov · 3 weeks later", f1(K["still"]), "km² still wet", "The water drained slowly. Damage teams follow where it lingers.")]
    stage = "".join(f'<img class="sc-ly{" on" if i == 0 else ""}" data-ly="{k}" src="{IMG}opera-{k}.webp" alt="" width="{W}" height="{H}" loading="lazy" />' for i, (k, *_r) in enumerate(steps))
    st = "".join(f'<li class="sc-step" data-ly="{k}"><p class="eyebrow">{e(t)}</p><strong class="grad">{e(v)}</strong><span class="u">{e(u)}</span><p>{e(l)}</p></li>' for k, t, v, u, l in steps)
    return f"""<section class="section tight" id="satellite"><div class="wrap">
{step_head(2, "What the satellite shows", "Radar maps the water through the storm.")}
{swipe}
<div class="sl-jump"><a class="btn ghost" href="#what-changed">See what changed ↓</a></div>
<div class="sc" id="what-changed">
  <div class="sc-stage"><div class="sc-frame">{stage}{zones_svg([])}<div class="sc-badge" aria-live="polite"><b>{f1(K['before'])}</b><span>km² new water</span></div>{legend(L_WATER, "on sc-lw")}{legend(L_DELTA, "on sc-ld")}</div>{legend(L_WATER, "below sc-lw")}{legend(L_DELTA, "below sc-ld")}</div>
  <ol class="sc-steps">{st}</ol>
</div>
</div></section>
"""

def actions():
    cards = ""
    for i, a in enumerate(ACTS):
        ly = a.get("layer", "after"); ly = "still" if ly == "still" else "delta" if ly == "delta" else "after"
        zs = [ZN[n] for n in a["zones"] if n in ZN]; tot = sum(z["added_km2" if ly == "delta" else "still_km2" if ly == "still" else "new_after_km2"] for z in zs)
        unit = "km² newly wet" if ly == "delta" else "km² still wet" if ly == "still" else "km² new water"
        assets = "".join(f'<li>{icon(t["asset"])}<span>{e(t["label"])}</span></li>' for t in a["tasks"])
        cards += f"""<article class="sa-card" data-fx="rise">
  <div class="sa-pic"><img src="/assets/img/{e(a['img'])}" alt="" loading="lazy" width="1152" height="864" />
    <a class="sa-map" href="/sar-change/app/#act={a['id']}" aria-label="Open this action on the ops map"><img src="{IMG}opera-{ly}.webp" alt="" loading="lazy" width="{W}" height="{H}" />{zones_svg(a['zones'], a.get('zones_alt', []), 'sa-zones')}<span>{len(zs)} towns · {f1(tot)} {unit}</span></a>
    <span class="sa-n">{i + 1}</span></div>
  <div class="sa-body">
    <p class="sa-cls">{e(a['cls'])} · {e(a.get('user', ''))}</p>
    <h3>{e(a['title'])}</h3>
    <p class="sa-why"><b>Because</b> {e(a['sat'])}</p>
    <ul class="sa-assets" aria-label="Who or what gets tasked">{assets}</ul>
    <div class="sa-cta"><a class="btn" href="/sar-change/app/#act={a['id']}">{e(a['verb'])} in the ops console →</a></div>
    <details class="sa-src"><summary>Evidence</summary><p>{e(a['src'])} Expected: {e(a['out'])}</p></details>
  </div></article>"""
    return f"""<section class="section tight" id="actions"><div class="wrap">
{step_head(3, "What we'll do", f"{len(ACTS)} actions. Each one names the towns the radar flagged.")}
<div class="sa-grid">{cards}</div>
<p class="fine">The ops console turns each action into tasks for crews, drones, cameras and the next satellite pass, with a live queue. Tasking there is simulated: nothing is sent to real teams or devices.</p>
</div></section>
"""

def impact():
    cards = ""
    for it in IMP:
        b = "".join(f"<li>{e(x)}</li>" for x in it["before"]); a = "".join(f"<li>{e(x)}</li>" for x in it["after"])
        cards += f"""<article class="si-card" data-fx="rise"><img src="/assets/img/{e(it['img'])}" alt="" loading="lazy" width="1152" height="864" />
  <div class="si-body"><p class="sa-cls">{e(it['user'])}</p><h3>{e(it['decision'])}</h3>
  <div class="si-ba"><div class="si-b"><p>Before</p><ul>{b}</ul></div><span aria-hidden="true">→</span><div class="si-a"><p>With SAR Change</p><ul>{a}</ul></div></div>
  <div class="si-nums"><div><small>From orbit</small><b>{e(it['geo']['v'])}</b><span>{e(it['geo']['l'])}</span></div><div><small>Model</small><b>{e(it['metric']['v'])}</b><span>{e(it['metric']['l'])}</span></div></div></div></article>"""
    nums = [(f"{f1(K['after'])} km²", "new water mapped through cloud, 31 Oct"), (IMP[0]["metric"]["v"], f"water IoU of our radar model (Otsu threshold: {K['otsu'] * 100:.1f}%)"),
            (f"{K['cpu_s']:.2f} s", "per 512 × 512 tile on a CPU"), ("p = 0.28", "no trend in the wettest day: we don't claim one")]
    strip = "".join(f'<li{" class=neg" if n.startswith("p =") else ""}><strong>{e(n)}</strong><span>{e(l)}</span></li>' for n, l in nums)
    return f"""<section class="section tight" id="impact"><div class="wrap">
{step_head(4, "Impact", "Two people, two decisions, before and after.")}
<div class="si-grid">{cards}</div>
<p class="mstrip-k">Backed by the radar data and the model tests · one seed, not a published benchmark</p><ul class="mstrip">{strip}</ul>
<p class="fine">Outcomes are qualitative: we haven't measured lives, damage or cost.</p>
</div></section>
"""

def override(slug, secs, A):
    secs["satellite"] = satellite(); secs["actions"] = actions(); secs["impact"] = impact()
    return secs
